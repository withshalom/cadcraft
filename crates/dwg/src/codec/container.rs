//! The 2004-family file container (ODA specification §4): AC1018 (2004), AC1024 (2010),
//! AC1027 (2013) and AC1032 (2018) share it.
//!
//! A file is a fixed header, an encrypted block that locates two system pages (the page map and the
//! section map), and data pages. Each named section (`AcDb:AcDbObjects`, `AcDb:Header`, ...) is a
//! run of pages, each compressed on its own. [`Container::read`] decodes the maps;
//! [`Container::section`] reassembles one section.

use super::bits::ByteReader;
use super::checksum::{crc32, page_checksum};
use super::{DecodeError, Limits, Result, capped, invalid, lz77};

/// The DWG versions this container serves.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Version {
    R2004,
    R2010,
    R2013,
    R2018,
}

impl Version {
    /// The version for a file's six-byte magic, if the 2004 container serves it.
    pub fn from_magic(magic: &[u8]) -> Option<Version> {
        match magic {
            b"AC1018" => Some(Version::R2004),
            b"AC1024" => Some(Version::R2010),
            b"AC1027" => Some(Version::R2013),
            b"AC1032" => Some(Version::R2018),
            _ => None,
        }
    }

    /// The file's version code.
    pub fn code(self) -> &'static str {
        match self {
            Version::R2004 => "AC1018",
            Version::R2010 => "AC1024",
            Version::R2013 => "AC1027",
            Version::R2018 => "AC1032",
        }
    }
}

/// Page-type markers (§4.3, §4.6).
const PAGE_MAP_TYPE: u32 = 0x4163_0E3B;
const SECTION_MAP_TYPE: u32 = 0x4163_003B;
const DATA_PAGE_TYPE: u32 = 0x4163_043B;
/// Where pages start: the page map's addresses count from here.
const FIRST_PAGE: u64 = 0x100;
/// Size of the encrypted header block at 0x80.
const HEADER_DATA_LEN: usize = 0x6C;

/// The byte sequence that masks the header block and fills page gaps (§4.1), generated by the
/// linear congruential generator the specification gives.
pub fn magic_sequence(len: usize) -> Vec<u8> {
    let mut seed: u32 = 1;
    (0..len)
        .map(|_| {
            seed = seed.wrapping_mul(0x343FD).wrapping_add(0x26_9EC3);
            (seed >> 16) as u8
        })
        .collect()
}

/// The decrypted 2004 file header data (§4.1), the fields a reader needs.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct HeaderData {
    pub last_page_id: u32,
    pub last_page_end: u64,
    pub second_header_address: u64,
    pub page_count: u32,
    pub page_map_id: u32,
    /// Absolute file address of the page map (the stored value plus 0x100).
    pub page_map_address: u64,
    pub section_map_id: u32,
    pub crc_ok: bool,
}

/// One entry of the page map: a page's number, file address and size. Gaps (negative numbers)
/// are kept so addresses stay right but are never read.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PageEntry {
    pub number: i32,
    pub address: u64,
    pub size: u64,
}

/// A page of a data section, from the section map.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SectionPage {
    pub number: u32,
    pub data_size: u32,
    pub start: u64,
}

/// A data section's description in the section map (§4.5).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SectionInfo {
    pub name: String,
    pub id: u32,
    pub size: u64,
    pub page_size: u32,
    pub compressed: bool,
    pub encrypted: u32,
    pub pages: Vec<SectionPage>,
}

/// A note about something that didn't check out but didn't stop reading.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Note(pub String);

/// The maps of a 2004-family file, ready to hand out sections.
#[derive(Clone, Debug)]
pub struct Container<'a> {
    file: &'a [u8],
    pub version: Version,
    /// The maintenance release version (file byte 0x0B).
    pub maintenance: u8,
    pub header: HeaderData,
    pub pages: Vec<PageEntry>,
    pub sections: Vec<SectionInfo>,
    pub notes: Vec<Note>,
    limits: Limits,
}

impl<'a> Container<'a> {
    /// Reads the header, the page map and the section map of `file`.
    pub fn read(file: &'a [u8], limits: Limits) -> Result<Container<'a>> {
        let magic = file.get(0..6).ok_or(DecodeError::Truncated("the version string"))?;
        let version = Version::from_magic(magic).ok_or_else(|| DecodeError::Unsupported(String::from_utf8_lossy(magic).into_owned()))?;
        let maintenance = file.get(0x0B).copied().ok_or(DecodeError::Truncated("the maintenance version"))?;
        let header = header_data(file)?;
        let mut notes = Vec::new();
        if !header.crc_ok {
            notes.push(Note("the file header's CRC doesn't match".into()));
        }
        let page_map = system_page(file, header.page_map_address, PAGE_MAP_TYPE, limits, &mut notes)?;
        let pages = page_entries(&page_map, limits)?;
        let section_map_page = pages
            .iter()
            .find(|p| i64::from(p.number) == i64::from(header.section_map_id))
            .ok_or_else(|| invalid("section map", format!("page {} is not in the page map", header.section_map_id)))?;
        let section_map = system_page(file, section_map_page.address, SECTION_MAP_TYPE, limits, &mut notes)?;
        let sections = section_infos(&section_map, limits)?;
        Ok(Container { file, version, maintenance, header, pages, sections, notes, limits })
    }

    /// The description of the section called `name`.
    pub fn info(&self, name: &str) -> Option<&SectionInfo> {
        self.sections.iter().find(|s| s.name == name)
    }

    /// The decompressed bytes of the section called `name`, or `None` when the file has none.
    pub fn section(&self, name: &str) -> Result<Option<Vec<u8>>> {
        match self.info(name) {
            Some(info) => self.section_data(info).map(Some),
            None => Ok(None),
        }
    }

    /// Reassembles a section from its pages (§4.5): pages in map order, omitted zero pages
    /// restored, each page cut to its logical length.
    pub fn section_data(&self, info: &SectionInfo) -> Result<Vec<u8>> {
        let size = capped("a section", info.size, self.limits.max_section_bytes)?;
        let size = usize::try_from(size).map_err(|_| invalid("section size", size.to_string()))?;
        let page_size = usize::try_from(info.page_size).map_err(|_| invalid("page size", info.page_size.to_string()))?;
        if page_size == 0 && size > 0 {
            return Err(invalid("page size", format!("0 for {}", info.name)));
        }
        let mut out = vec![0u8; size];
        for page in &info.pages {
            let start = usize::try_from(page.start).map_err(|_| invalid("page start", page.start.to_string()))?;
            if start >= size {
                continue;
            }
            let data = self.page(page, info, page_size)?;
            let take = data.len().min(page_size).min(size - start);
            let src = data.get(..take).ok_or(DecodeError::Truncated("a page"))?;
            let dst = out.get_mut(start..start + take).ok_or(invalid("page start", "past the section end"))?;
            dst.copy_from_slice(src);
        }
        Ok(out)
    }

    /// One data page, decompressed when the section is compressed.
    fn page(&self, page: &SectionPage, info: &SectionInfo, page_size: usize) -> Result<Vec<u8>> {
        let entry = self
            .pages
            .iter()
            .find(|p| i64::from(p.number) == i64::from(page.number))
            .ok_or_else(|| invalid("section page", format!("page {} of {} is not in the page map", page.number, info.name)))?;
        let header = data_page_header(self.file, entry.address)?;
        let body_start = usize::try_from(entry.address.saturating_add(32)).map_err(|_| invalid("page address", entry.address.to_string()))?;
        let len = usize::try_from(header.data_size).map_err(|_| invalid("page data size", header.data_size.to_string()))?;
        let body = self.file.get(body_start..body_start.saturating_add(len)).ok_or(DecodeError::Truncated("a data page"))?;
        if info.compressed { lz77::decompress(body, page_size) } else { Ok(body.to_vec()) }
    }
}

/// Decrypts and checks the 0x6C-byte header block at 0x80 (§4.1).
pub fn header_data(file: &[u8]) -> Result<HeaderData> {
    let raw = file.get(0x80..0x80 + HEADER_DATA_LEN).ok_or(DecodeError::Truncated("the file header"))?;
    let mask = magic_sequence(HEADER_DATA_LEN);
    let mut data: Vec<u8> = raw.iter().zip(&mask).map(|(a, b)| a ^ b).collect();
    if data.get(0..12) != Some(b"AcFssFcAJMB\0".as_slice()) {
        return Err(invalid("file header", "the file ID string is missing"));
    }
    let mut r = ByteReader::new(&data);
    r.take(0x28)?;
    let last_page_id = r.u32_le()?;
    let last_page_end = r.u64_le()?;
    let second_header_address = r.u64_le()?;
    let _gap_amount = r.u32_le()?;
    let page_count = r.u32_le()?;
    r.take(12)?;
    let page_map_id = r.u32_le()?;
    let page_map_address = r.u64_le()?.checked_add(FIRST_PAGE).ok_or(invalid("page map address", "overflows"))?;
    let section_map_id = r.u32_le()?;
    r.take(8)?;
    let stored_crc = r.u32_le()?;
    if let Some(crc_field) = data.get_mut(0x68..0x6C) {
        crc_field.fill(0);
    }
    let crc_ok = crc32(0, &data) == stored_crc;
    Ok(HeaderData { last_page_id, last_page_end, second_header_address, page_count, page_map_id, page_map_address, section_map_id, crc_ok })
}

/// Reads and decompresses the system page at `address`, which must be of type `kind` (§4.3).
fn system_page(file: &[u8], address: u64, kind: u32, limits: Limits, notes: &mut Vec<Note>) -> Result<Vec<u8>> {
    let at = usize::try_from(address).map_err(|_| invalid("system page address", address.to_string()))?;
    let head = file.get(at..at.saturating_add(0x14)).ok_or(DecodeError::Truncated("a system page header"))?;
    let mut r = ByteReader::new(head);
    let page_type = r.u32_le()?;
    if page_type != kind {
        return Err(invalid("system page", format!("type {page_type:#010x} where {kind:#010x} was expected")));
    }
    let decompressed = u64::from(r.u32_le()?);
    let compressed = r.u32_le()?;
    let compression = r.u32_le()?;
    let stored_checksum = r.u32_le()?;
    let decompressed = usize::try_from(capped("a system page", decompressed, limits.max_section_bytes)?)
        .map_err(|_| invalid("system page size", decompressed.to_string()))?;
    let body_start = at + 0x14;
    let len = usize::try_from(compressed).map_err(|_| invalid("system page size", compressed.to_string()))?;
    let body = file.get(body_start..body_start.saturating_add(len)).ok_or(DecodeError::Truncated("a system page"))?;
    let mut zeroed = head.to_vec();
    if let Some(field) = zeroed.get_mut(0x10..0x14) {
        field.fill(0);
    }
    if page_checksum(page_checksum(0, &zeroed), body) != stored_checksum {
        notes.push(Note(format!("system page {kind:#010x} checksum doesn't match")));
    }
    match compression {
        2 => lz77::decompress(body, decompressed),
        1 => Ok(body.to_vec()),
        other => Err(invalid("system page compression", other.to_string())),
    }
}

/// The page map entries with their addresses (§4.4).
fn page_entries(map: &[u8], limits: Limits) -> Result<Vec<PageEntry>> {
    let mut r = ByteReader::new(map);
    let mut address = FIRST_PAGE;
    let mut pages = Vec::new();
    while r.remaining() >= 8 {
        if pages.len() >= limits.max_pages as usize {
            return Err(DecodeError::TooLarge { what: "the page map", size: pages.len() as u64, limit: u64::from(limits.max_pages) });
        }
        let number = r.i32_le()?;
        let size = u64::from(r.u32_le()?);
        if number < 0 {
            r.take(16)?;
        }
        pages.push(PageEntry { number, address, size });
        address = address.checked_add(size).ok_or(invalid("page map", "addresses overflow"))?;
    }
    Ok(pages)
}

/// The section descriptions and their page lists (§4.5).
fn section_infos(map: &[u8], limits: Limits) -> Result<Vec<SectionInfo>> {
    let mut r = ByteReader::new(map);
    let count = r.u32_le()?;
    capped("the section map", u64::from(count), u64::from(limits.max_sections))?;
    r.take(16)?;
    let mut sections = Vec::with_capacity(count as usize);
    for _ in 0..count {
        sections.push(section_info(&mut r, limits)?);
    }
    Ok(sections)
}

fn section_info(r: &mut ByteReader<'_>, limits: Limits) -> Result<SectionInfo> {
    let size = r.u64_le()?;
    let page_count = r.u32_le()?;
    capped("a section's page list", u64::from(page_count), u64::from(limits.max_pages))?;
    let page_size = r.u32_le()?;
    let _unknown = r.u32_le()?;
    let compressed = r.u32_le()? == 2;
    let id = r.u32_le()?;
    let encrypted = r.u32_le()?;
    let name_bytes = r.take(64)?;
    let name_len = name_bytes.iter().position(|&b| b == 0).unwrap_or(name_bytes.len());
    let name = String::from_utf8_lossy(name_bytes.get(..name_len).unwrap_or_default()).into_owned();
    let mut pages = Vec::with_capacity(page_count as usize);
    for _ in 0..page_count {
        pages.push(SectionPage { number: r.u32_le()?, data_size: r.u32_le()?, start: r.u64_le()? });
    }
    Ok(SectionInfo { name, id, size, page_size, compressed, encrypted, pages })
}

/// The decoded 32-byte header of a data page (§4.6).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DataPageHeader {
    pub section: u32,
    pub data_size: u32,
    pub page_size: u32,
    pub start: u64,
    pub header_checksum: u32,
    pub data_checksum: u32,
}

/// Unmasks and decodes the header of the data page at `address`.
pub fn data_page_header(file: &[u8], address: u64) -> Result<DataPageHeader> {
    let at = usize::try_from(address).map_err(|_| invalid("data page address", address.to_string()))?;
    let raw = file.get(at..at.saturating_add(32)).ok_or(DecodeError::Truncated("a data page header"))?;
    let mask = (0x4164_536B_u32 ^ (address as u32)).to_le_bytes();
    let plain: Vec<u8> = raw.iter().enumerate().map(|(i, b)| b ^ mask[i % 4]).collect();
    let mut r = ByteReader::new(&plain);
    let page_type = r.u32_le()?;
    if page_type != DATA_PAGE_TYPE {
        return Err(invalid("data page", format!("type {page_type:#010x} at {address:#x}")));
    }
    Ok(DataPageHeader {
        section: r.u32_le()?,
        data_size: r.u32_le()?,
        page_size: r.u32_le()?,
        start: r.u64_le()?,
        header_checksum: r.u32_le()?,
        data_checksum: r.u32_le()?,
    })
}
